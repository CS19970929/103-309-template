#ifndef PROJECT_BUILD_GUARD_H
#define PROJECT_BUILD_GUARD_H

#include "Project_Config.h"

#define PROJECT_BUILD_PROFILE_RELEASE       0
#define PROJECT_BUILD_PROFILE_DEBUG         1
#define PROJECT_BUILD_PROFILE_FACTORY_TEST  2

#ifndef PROJECT_CFG_SOC_TEST_MODE_ENABLE
#define PROJECT_CFG_SOC_TEST_MODE_ENABLE 0
#endif

#ifndef PROJECT_CFG_SOC_TEST_ACCEL_TICKS_MAX
#define PROJECT_CFG_SOC_TEST_ACCEL_TICKS_MAX 300
#endif

#endif

/* Checks stay outside the include guard so late-defined macros are still caught. */
#if (PROJECT_CFG_BUILD_PROFILE != PROJECT_BUILD_PROFILE_RELEASE) && \
    (PROJECT_CFG_BUILD_PROFILE != PROJECT_BUILD_PROFILE_DEBUG) && \
    (PROJECT_CFG_BUILD_PROFILE != PROJECT_BUILD_PROFILE_FACTORY_TEST)
#error "Invalid PROJECT_CFG_BUILD_PROFILE"
#endif

#if (PROJECT_CFG_SOC_FULL_CONFIRM_MIN_CELL_MARGIN_MV > 500)
#error "Invalid PROJECT_CFG_SOC_FULL_CONFIRM_MIN_CELL_MARGIN_MV"
#endif

#if (PROJECT_CFG_SOC_FULL_CONFIRM_MAX_CELL_DELTA_MV > 1000)
#error "Invalid PROJECT_CFG_SOC_FULL_CONFIRM_MAX_CELL_DELTA_MV"
#endif

#if (PROJECT_CFG_SOC_FULL_CONFIRM_SECONDS < 1) || \
    (PROJECT_CFG_SOC_FULL_CONFIRM_SECONDS > 600)
#error "Invalid PROJECT_CFG_SOC_FULL_CONFIRM_SECONDS"
#endif

#if (PROJECT_CFG_SOC_FULL_CONFIRM_FAST_SECONDS < 1) || \
    (PROJECT_CFG_SOC_FULL_CONFIRM_FAST_SECONDS > 600)
#error "Invalid PROJECT_CFG_SOC_FULL_CONFIRM_FAST_SECONDS"
#endif

#if (PROJECT_CFG_SOC_FULL_CONFIRM_FAST_SECONDS > PROJECT_CFG_SOC_FULL_CONFIRM_SECONDS)
#error "SOC full fast confirm time must not exceed normal confirm time"
#endif

#if (PROJECT_CFG_SOC_FULL_CONFIRM_MIN_SOC_PERCENT > 100)
#error "Invalid PROJECT_CFG_SOC_FULL_CONFIRM_MIN_SOC_PERCENT"
#endif

#if (PROJECT_CFG_SOC_FULL_CONFIRM_FAST_MARGIN_MV > 500)
#error "Invalid PROJECT_CFG_SOC_FULL_CONFIRM_FAST_MARGIN_MV"
#endif

#if (PROJECT_CFG_SOC_CALIBRATION_MIN_CELL_VALID_MV < 1000) || \
    (PROJECT_CFG_SOC_CALIBRATION_MIN_CELL_VALID_MV > 3500)
#error "Invalid PROJECT_CFG_SOC_CALIBRATION_MIN_CELL_VALID_MV"
#endif

#if (PROJECT_CFG_SOC_CALIBRATION_MAX_CELL_VALID_MV < 3600) || \
    (PROJECT_CFG_SOC_CALIBRATION_MAX_CELL_VALID_MV > 6000)
#error "Invalid PROJECT_CFG_SOC_CALIBRATION_MAX_CELL_VALID_MV"
#endif

#if (PROJECT_CFG_SOC_CALIBRATION_MIN_CELL_VALID_MV >= PROJECT_CFG_SOC_CALIBRATION_MAX_CELL_VALID_MV)
#error "SOC calibration min voltage must be less than max voltage"
#endif

#if (PROJECT_CFG_SOC_CALIBRATION_MAX_CELL_DELTA_MV > 3000)
#error "Invalid PROJECT_CFG_SOC_CALIBRATION_MAX_CELL_DELTA_MV"
#endif

#if (PROJECT_CFG_SOC_CALIBRATION_BLOCK_PROTECTION_FAULT != 0) && \
    (PROJECT_CFG_SOC_CALIBRATION_BLOCK_PROTECTION_FAULT != 1)
#error "Invalid PROJECT_CFG_SOC_CALIBRATION_BLOCK_PROTECTION_FAULT"
#endif

#if (PROJECT_CFG_SOC_CALIBRATION_BLOCK_SYSTEM_FAULT != 0) && \
    (PROJECT_CFG_SOC_CALIBRATION_BLOCK_SYSTEM_FAULT != 1)
#error "Invalid PROJECT_CFG_SOC_CALIBRATION_BLOCK_SYSTEM_FAULT"
#endif

#if (PROJECT_CFG_SOC_SAG_HOLDOFF_SECONDS > 1800)
#error "Invalid PROJECT_CFG_SOC_SAG_HOLDOFF_SECONDS"
#endif

#if (PROJECT_CFG_SOC_SAG_ALLOW_OFFSET_MV > 500)
#error "Invalid PROJECT_CFG_SOC_SAG_ALLOW_OFFSET_MV"
#endif

#if (PROJECT_CFG_SOC_REST_OCV_SECONDS < 60) || \
    (PROJECT_CFG_SOC_REST_OCV_SECONDS > 43200)
#error "Invalid PROJECT_CFG_SOC_REST_OCV_SECONDS"
#endif

#if (PROJECT_CFG_SOC_CALIBRATION_STEP_PERCENT < 1) || \
    (PROJECT_CFG_SOC_CALIBRATION_STEP_PERCENT > 10)
#error "Invalid PROJECT_CFG_SOC_CALIBRATION_STEP_PERCENT"
#endif

#if (PROJECT_CFG_SOC_TEST_MODE_ENABLE != 0) && \
    (PROJECT_CFG_SOC_TEST_MODE_ENABLE != 1)
#error "Invalid PROJECT_CFG_SOC_TEST_MODE_ENABLE"
#endif

#if (PROJECT_CFG_SOC_TEST_ACCEL_TICKS_MAX < 1) || \
    (PROJECT_CFG_SOC_TEST_ACCEL_TICKS_MAX > 1000)
#error "Invalid PROJECT_CFG_SOC_TEST_ACCEL_TICKS_MAX"
#endif

#if PROJECT_CFG_SOC_TEST_MODE_ENABLE && \
    (PROJECT_CFG_BUILD_PROFILE != PROJECT_BUILD_PROFILE_FACTORY_TEST)
#error "SOC test mode requires Factory/Test build profile"
#endif

#if (PROJECT_CFG_BUILD_PROFILE == PROJECT_BUILD_PROFILE_RELEASE)

#if !PROJECT_CFG_WDOG_ENABLE
#error "Release build: PROJECT_CFG_WDOG_ENABLE must be 1"
#endif

#if PROJECT_CFG_DEBUG_CODE_ENABLE
#error "Release build: PROJECT_CFG_DEBUG_CODE_ENABLE must be 0"
#endif

#if PROJECT_CFG_FLASH64K_QUICK_TEST_ENABLE
#error "Release build: PROJECT_CFG_FLASH64K_QUICK_TEST_ENABLE must be 0"
#endif

#if PROJECT_CFG_FLASH64K_USE_TEST_ENABLE
#error "Release build: PROJECT_CFG_FLASH64K_USE_TEST_ENABLE must be 0"
#endif

#if PROJECT_CFG_LEDBAR_LONG_PRESS_GPIO_TOGGLE_TEST
#error "Release build: PROJECT_CFG_LEDBAR_LONG_PRESS_GPIO_TOGGLE_TEST must be 0"
#endif

#if PROJECT_CFG_UPGRADE_PARAM_FORCE_REAPPLY
#error "Release build: PROJECT_CFG_UPGRADE_PARAM_FORCE_REAPPLY must be 0"
#endif

#if defined(_DEBUG_)
#error "Release build: remove _DEBUG_ from Keil defines or select Debug profile"
#endif

#if defined(_DEBUG_CODE)
#error "Release build: _DEBUG_CODE must not be defined"
#endif

#if defined(FLASH64K_APP_QUICK_TEST_ENABLE)
#error "Release build: FLASH64K_APP_QUICK_TEST_ENABLE must not be defined"
#endif

#if defined(FLASH64K_APP_USE_TEST_ENABLE)
#error "Release build: FLASH64K_APP_USE_TEST_ENABLE must not be defined"
#endif

#if defined(ELOG_OUTPUT_ENABLE)
#error "Release build: ELOG_OUTPUT_ENABLE must not be defined"
#endif

#endif
