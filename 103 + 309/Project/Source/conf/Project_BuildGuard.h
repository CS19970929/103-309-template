#ifndef PROJECT_BUILD_GUARD_H
#define PROJECT_BUILD_GUARD_H

#include "Project_Config.h"

#if (PROJECT_CFG_BAT_CHEMISTRY != 0) && (PROJECT_CFG_BAT_CHEMISTRY != 1)
#error "Invalid PROJECT_CFG_BAT_CHEMISTRY"
#endif
#if (PROJECT_CFG_HOST_WRITE_ENABLE != 0) && (PROJECT_CFG_HOST_WRITE_ENABLE != 1)
#error "Invalid PROJECT_CFG_HOST_WRITE_ENABLE"
#endif
#if (PROJECT_CFG_RESET_PARAMS_ON_NEW_VERSION != 0) && (PROJECT_CFG_RESET_PARAMS_ON_NEW_VERSION != 1)
#error "PROJECT_CFG_RESET_PARAMS_ON_NEW_VERSION must be 0 or 1"
#endif
#if (PROJECT_CFG_SWITCH_MODE != PROJECT_SWITCH_MAINTAINED) && \
    (PROJECT_CFG_SWITCH_MODE != PROJECT_SWITCH_PUSHBUTTON)
#error "PROJECT_CFG_SWITCH_MODE must be 0 (maintained) or 1 (pushbutton)"
#endif
#if (PROJECT_CFG_PARAM_AFE_VERSION < 0) || (PROJECT_CFG_PARAM_AFE_VERSION > 65534) || \
    (PROJECT_CFG_PARAM_PROTECT_VERSION < 0) || (PROJECT_CFG_PARAM_PROTECT_VERSION > 65534) || \
    (PROJECT_CFG_PARAM_SOC_VERSION < 0) || (PROJECT_CFG_PARAM_SOC_VERSION > 65534) || \
    (PROJECT_CFG_PARAM_OTHER_VERSION < 0) || (PROJECT_CFG_PARAM_OTHER_VERSION > 65534) || \
    (PROJECT_CFG_PARAM_CALIB_VERSION < 0) || (PROJECT_CFG_PARAM_CALIB_VERSION > 65534) || \
    (PROJECT_CFG_PARAM_HEAT_COOL_VERSION < 0) || (PROJECT_CFG_PARAM_HEAT_COOL_VERSION > 65534) || \
    (PROJECT_CFG_PARAM_SOC_STATE_VERSION < 0) || (PROJECT_CFG_PARAM_SOC_STATE_VERSION > 65534) || \
    (PROJECT_CFG_PARAM_AGING_STATE_VERSION < 0) || (PROJECT_CFG_PARAM_AGING_STATE_VERSION > 65534) || \
    (PROJECT_CFG_PARAM_LOG_VERSION < 0) || (PROJECT_CFG_PARAM_LOG_VERSION > 65534)
#error "Module parameter versions must be 0 (preserve) or 1..65534"
#endif
#if (PROJECT_CFG_LOG_RECORD_REPEAT_MIN_INTERVAL_SEC > 86400)
#error "Invalid PROJECT_CFG_LOG_RECORD_REPEAT_MIN_INTERVAL_SEC"
#endif

#endif /* PROJECT_BUILD_GUARD_H */
